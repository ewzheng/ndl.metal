class BroadcastTo(TensorOp):
    def __init__(self, shape):
        self.shape = shape

    def compute(self, a):
        ### BEGIN YOUR SOLUTION
        return array_api.broadcast_to(a, self.shape)
        ### END YOUR SOLUTION

    def gradient(self, out_grad, node):
        ### BEGIN YOUR SOLUTION
        in_shape = (1,) * (len(self.shape) - len(node.inputs[0].shape)) + (node.inputs[0].shape)
        axes = list()
        for i in range(len(self.shape)):
          if in_shape[i] != self.shape[i]:
            axes.append(i)
        axes = tuple(axes)

        return reshape(summation(out_grad, axes), node.inputs[0].shape)
        ### END YOUR SOLUTION


def broadcast_to(a, shape):
    return BroadcastTo(shape)(a)


class Summation(TensorOp):
    def __init__(self, axes: Optional[tuple] = None):
        self.axes = axes

    def compute(self, a):
        ### BEGIN YOUR SOLUTION
        return array_api.sum(a, axis=self.axes)
        ### END YOUR SOLUTION

    def gradient(self, out_grad, node):
        ### BEGIN YOUR SOLUTION
  
        sum_shape = list(node.inputs[0].shape)
        axes = self.axes

        # handle some edge cases
        if self.axes == None:
          axes = range(len(sum_shape))
        elif type(self.axes) != tuple:
          axes = (self.axes,) 
        
        for axis in axes:
          sum_shape[axis] = 1
        
        return broadcast_to(reshape(out_grad, sum_shape), node.inputs[0].shape)
        ### END YOUR SOLUTION


def summation(a, axes=None):
    return Summation(axes)(a)


class MatMul(TensorOp):
    def compute(self, a, b):
        ### BEGIN YOUR SOLUTION
        return a @ b
        ### END YOUR SOLUTION

    def gradient(self, out_grad, node):
        ### BEGIN YOUR SOLUTION
        a, b = node.inputs

        a_grad = matmul(out_grad, transpose(b))
        b_grad = matmul(transpose(a), out_grad)

        a_extra = len(a_grad.shape) - len(a.shape)
        b_extra = len(b_grad.shape) - len(b.shape)

        if a_extra > 0:
          a_grad = summation(a_grad, tuple(range(a_extra)))
        if b_extra > 0:
          b_grad = summation(b_grad, tuple(range(b_extra)))

        return a_grad, b_grad
        ### END YOUR SOLUTION


def matmul(a, b):
    return MatMul()(a, b)


